"""Compare models for each agent on the labelled transcripts in evals/dataset.json,
and measure sequential vs parallel pipeline latency.

Run from the repo root with OPENAI_API_KEY set (in the environment or Backend/.env):

    python evals/run_eval.py              # all transcripts, gpt-4o vs gpt-4o-mini
    python evals/run_eval.py --limit 3    # quick, cheaper run

Writes evals/results.json and evals/RESULTS.md.
"""
import argparse
import asyncio
import json
import sys
import time
from pathlib import Path

EVALS_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(EVALS_DIR.parent / "Backend"))
sys.path.insert(0, str(EVALS_DIR))

from agents.base import DEFAULT_MODELS  # noqa: E402
from agents.email_drafter import run_email_drafter  # noqa: E402
from agents.extractor import run_extractor  # noqa: E402
from agents.summarizer import run_summarizer  # noqa: E402
from scoring import (  # noqa: E402
    aggregate_extraction, mean, pass_rate, score_email, score_extraction, score_summary,
)

PIPELINE_AGENTS = ["extractor", "summarizer", "email_drafter"]

def load_samples(limit):
    samples = json.loads((EVALS_DIR / "dataset.json").read_text(encoding="utf-8"))
    for sample in samples:
        sample["text"] = "\n".join(sample["transcript"])
    return samples[:limit] if limit else samples

def run_stats(runs):
    llm_runs = [r for r in runs if r.prompt_tokens or r.completion_tokens]
    return {
        "avg_seconds": mean(r.seconds for r in llm_runs),
        "avg_cost_usd": mean(r.cost_usd for r in llm_runs),
        "fallbacks": sum(r.fallback for r in runs),
    }

async def evaluate_model(model, samples):
    extraction_scores, summary_checks, email_checks = [], [], []
    runs = {name: [] for name in PIPELINE_AGENTS}

    for sample in samples:
        print(f"  [{model}] {sample['id']}", flush=True)
        extraction = await run_extractor(sample["text"], model=model)
        summary = await run_summarizer(sample["text"], model=model)
        # The drafter gets the gold items, so every model is judged on identical input
        gold_items = [{**item, "status": "pending"} for item in sample["action_items"]]
        email = await run_email_drafter(gold_items, summary.data, model=model)

        runs["extractor"].append(extraction)
        runs["summarizer"].append(summary)
        runs["email_drafter"].append(email)

        extraction_scores.append(score_extraction(extraction.data["action_items"], sample["action_items"]))
        summary_checks.append(score_summary(summary.data))
        if gold_items:
            email_checks.append(score_email(email.data, gold_items))

    return {
        "extractor": {**aggregate_extraction(extraction_scores), **run_stats(runs["extractor"])},
        "summarizer": {**pass_rate(summary_checks), **run_stats(runs["summarizer"])},
        "email_drafter": {**pass_rate(email_checks), **run_stats(runs["email_drafter"])},
    }

async def run_pipeline(transcript, parallel):
    start = time.perf_counter()
    if parallel:
        extraction, summary = await asyncio.gather(run_extractor(transcript), run_summarizer(transcript))
    else:
        extraction = await run_extractor(transcript)
        summary = await run_summarizer(transcript)
    await run_email_drafter(extraction.data["action_items"], summary.data)
    return time.perf_counter() - start

async def measure_latency(samples):
    sequential, parallel = [], []
    for index, sample in enumerate(samples):
        print(f"  [latency] {sample['id']}", flush=True)
        # Alternate the order so neither mode always benefits from a warm connection
        for mode in ([False, True] if index % 2 == 0 else [True, False]):
            seconds = await run_pipeline(sample["text"], parallel=mode)
            (parallel if mode else sequential).append(seconds)
    return {"sequential_avg_seconds": mean(sequential), "parallel_avg_seconds": mean(parallel)}

def pipeline_costs(results, models):
    configs = {"production": {name: DEFAULT_MODELS[name] for name in PIPELINE_AGENTS}}
    for model in models:
        configs[f"all {model}"] = {name: model for name in PIPELINE_AGENTS}
    return {
        label: sum(results[config[name]][name]["avg_cost_usd"] for name in PIPELINE_AGENTS)
        for label, config in configs.items()
        if all(config[name] in results for name in PIPELINE_AGENTS)
    }

def to_markdown(report):
    models = report["models"]
    pct = lambda v: f"{v * 100:.0f}%"  # noqa: E731
    lines = [
        "# Evaluation Results",
        "",
        f"{report['samples']} labelled transcripts · generated by `python evals/run_eval.py` on {report['date']}",
        "",
        "## Action-item extraction",
        "",
        "| Model | Precision | Recall | F1 | Assignee accuracy | Avg latency | Avg cost |",
        "|---|---|---|---|---|---|---|",
    ]
    for model in models:
        r = report["results"][model]["extractor"]
        lines.append(f"| {model} | {pct(r['precision'])} | {pct(r['recall'])} | {pct(r['f1'])} | "
                     f"{pct(r['assignee_accuracy'])} | {r['avg_seconds']:.1f}s | ${r['avg_cost_usd']:.5f} |")

    lines += ["", "## Summaries (format compliance)", "",
              "| Model | Under 100 words | 2-3 key points | No markdown | Has decisions | Avg latency | Avg cost |",
              "|---|---|---|---|---|---|---|"]
    for model in models:
        r = report["results"][model]["summarizer"]
        lines.append(f"| {model} | {pct(r['under_100_words'])} | {pct(r['two_to_three_points'])} | "
                     f"{pct(r['no_markdown'])} | {pct(r['has_decisions'])} | {r['avg_seconds']:.1f}s | ${r['avg_cost_usd']:.5f} |")

    lines += ["", "## Follow-up emails", "",
              "| Model | Items covered | Owners named | No markdown | Under 250 words | Avg latency | Avg cost |",
              "|---|---|---|---|---|---|---|"]
    for model in models:
        r = report["results"][model]["email_drafter"]
        lines.append(f"| {model} | {pct(r['item_coverage'])} | {pct(r['owner_coverage'])} | "
                     f"{pct(r['no_markdown'])} | {pct(r['under_250_words'])} | {r['avg_seconds']:.1f}s | ${r['avg_cost_usd']:.5f} |")

    lines += ["", "## Cost per meeting (extractor + summarizer + email drafter)", "",
              "| Configuration | Avg cost per meeting |", "|---|---|"]
    for label, cost in report["pipeline_costs"].items():
        lines.append(f"| {label} | ${cost:.5f} |")

    if report.get("latency"):
        lat = report["latency"]
        change = 1 - lat["parallel_avg_seconds"] / lat["sequential_avg_seconds"] if lat["sequential_avg_seconds"] else 0
        direction = "faster" if change >= 0 else "slower"
        lines += ["", "## Pipeline latency (production models)", "",
                  "| Mode | Avg end-to-end time |", "|---|---|",
                  f"| Sequential | {lat['sequential_avg_seconds']:.1f}s |",
                  f"| Parallel (extractor + summarizer together) | {lat['parallel_avg_seconds']:.1f}s ({abs(change) * 100:.0f}% {direction}) |"]

    fallbacks = sum(report["results"][m][a]["fallbacks"] for m in models for a in PIPELINE_AGENTS)
    lines += ["", f"Structured-output fallbacks across all runs: {fallbacks}", ""]
    return "\n".join(lines)

async def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--models", nargs="+", default=["gpt-4o", "gpt-4o-mini"])
    parser.add_argument("--limit", type=int, default=None, help="only use the first N transcripts")
    parser.add_argument("--skip-latency", action="store_true", help="skip the sequential vs parallel timing runs")
    args = parser.parse_args()

    samples = load_samples(args.limit)
    print(f"Evaluating {len(samples)} transcripts with {', '.join(args.models)}")

    results = {model: await evaluate_model(model, samples) for model in args.models}
    report = {
        "date": time.strftime("%Y-%m-%d"),
        "samples": len(samples),
        "models": args.models,
        "results": results,
        "pipeline_costs": pipeline_costs(results, args.models),
        "latency": None if args.skip_latency else await measure_latency(samples),
    }

    (EVALS_DIR / "results.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    markdown = to_markdown(report)
    (EVALS_DIR / "RESULTS.md").write_text(markdown, encoding="utf-8")
    print("\n" + markdown)

if __name__ == "__main__":
    asyncio.run(main())
